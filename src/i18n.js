function initialLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (LANGS.includes(stored)) return stored;
  } catch { /* storage unavailable */ }
  return navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

let lang = initialLang();
const listeners = new Set();

export const getLang = () => lang;

/** Translated string for `key`, with {placeholders} filled from `vars`. Falls back to English. */
export function t(key, vars = {}) {
  const template = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
}

/** Plural form of `key` (key_one / key_other) for count n. French: 0 and 1 are singular. */
export function tn(key, n, vars = {}) {
  const one = lang === 'fr' ? Math.abs(n) < 2 : n === 1;
  return t(`${key}_${one ? 'one' : 'other'}`, { n, ...vars });
}

/** A number of seconds from milliseconds, e.g. "1.2 s" / "1,2 s". */
export const formatSeconds = (ms) =>
  `${(ms / 1000).toLocaleString(lang, { minimumFractionDigits: 1, maximumFractionDigits: 1 })} s`;

/** Re-translates every tagged element under `root`. */
export function applyTranslations(root = document) {
  document.documentElement.lang = lang;
  document.title = t('page.title');
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
}

export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  applyTranslations();
  for (const fn of listeners) fn(lang);
}

/** Calls fn(lang) after every language switch; returns an unsubscribe function. */
export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}
